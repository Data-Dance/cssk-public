"""Engine-neutral fund evidence; no payroll engine is imported here.

Each bridge owns the JSON/storage field ``l10n_sk_fund_assessment``, inherits
this mixin alongside its native hr.payslip and supplies
_l10n_sk_fund_identity and _l10n_sk_version (the contract version the payslip
is computed on); actual charged bases are supplied by salary rules, never
reconstructed here. The bridge also owns its capture hooks, its
compute_sheet wrapper, refund pairing and direction. Confirmation, source
locking and native child-row policies belong to the engine's lifecycle
adapter, not to this abstract protocol.
"""

from copy import deepcopy

from odoo import _, models
from odoo.exceptions import UserError

from ..fund_assessment import fund_assessment, index_assessments
from ..fund_capture import (
    CAPTURE_KEY,
    _FundCapture,
    may_write_evidence,
    writer_context,
)


class FundEvidenceError(UserError):
    """An unreadable record is missing evidence, not a payroll/ACL failure."""


class PayslipFundMixin(models.AbstractModel):
    _name = "l10n.sk.payslip.fund.mixin"
    _description = "Recorded payroll fund evidence"

    def l10n_sk_fund_record(self, fund, side, base, rate, amount, facts=None):
        """Rule helper returning data only; RPC cannot write generated evidence."""
        self.ensure_one()
        try:
            return fund_assessment(
                fund=fund, side=side, base=base, rate=rate, amount=amount, facts=facts
            )
        except ValueError:
            return False  # Optional metadata must not stop native payroll.

    # ------------------------------------------------------------------
    # Recording (called by the engine bridge)
    # ------------------------------------------------------------------
    def _l10n_sk_check_fund_evidence_values(self, values_list):
        """Refuse generated evidence supplied by a caller or a context default.

        The bridge calls this from its create/write; its own store passes.
        """
        if may_write_evidence(self.env.context):
            return
        if "default_l10n_sk_fund_assessment" in self.env.context or any(
            "l10n_sk_fund_assessment" in values for values in values_list
        ):
            raise UserError(_("Fund evidence is generated by payroll calculation."))

    def _l10n_sk_store_fund_evidence(self, evidence):
        """Write generated evidence (or False) past the bridge's guard."""
        return self.with_context(**writer_context()).write(
            {"l10n_sk_fund_assessment": evidence}
        )

    def _l10n_sk_is_recording_funds(self):
        self.ensure_one()
        capture = self.env.context.get(CAPTURE_KEY)
        return isinstance(capture, _FundCapture) and self.id in capture.supported

    def _l10n_sk_fund_salary_facts(self):
        self.ensure_one()
        return sorted(
            [
                [
                    line.code,
                    line.salary_rule_id.id,
                    line.amount,
                    line.quantity,
                    line.rate,
                    line.total,
                ]
                for line in self.line_ids
            ]
        )

    def _l10n_sk_fund_profile(self):
        """Store the statutory profile once; never copy restricted birth numbers."""
        version = self._l10n_sk_version()
        return {
            "version": version.id,
            "agreement": version.l10n_sk_employment_form(),
            "pension": version.l10n_sk_pension_status(),
            "regular": version.l10n_sk_income_is_regular(),
            "oop": version.l10n_sk_agreement_oop,
            "guarantee_exempt": version.l10n_sk_guarantee_exempt,
        }

    def _l10n_sk_fund_evidence(self, rows):
        """The stored evidence (schema 1) for finalised rows of this payslip."""
        self.ensure_one()
        return {
            "schema": 1,
            "complete": True,
            "records": rows,
            "identity": self._l10n_sk_fund_identity(),
            "salary": self._l10n_sk_fund_salary_facts(),
            "profile": self._l10n_sk_fund_profile(),
        }

    def _l10n_sk_store_captured_funds(self, capture):
        """Store evidence for each payslip whose capture produced rows."""
        for slip in self:
            rows = capture.rows.get(slip.id)
            if rows:
                slip._l10n_sk_store_fund_evidence(slip._l10n_sk_fund_evidence(rows))

    # ------------------------------------------------------------------
    # Reading
    # ------------------------------------------------------------------
    def _l10n_sk_refund_original(self):
        """The engine's confirmed original this refund mirrors, or empty."""
        return self.browse()

    def _l10n_sk_read_recorded_fund_bases(self):
        """Reader skeleton: a paired refund borrows its original's rows.

        The bridge exposes it as ``_cssk_recorded_fund_bases``; an engine that
        does not is not read at all (declarations keep the old workflow).
        """
        self.ensure_one()
        self.check_access("read")
        original = self._l10n_sk_refund_original()
        if original:
            return [
                dict(row, facts=dict(row["facts"], refund_of_payslip=original.id))
                for row in deepcopy(original._l10n_sk_read_recorded_fund_bases() or [])
            ] or False
        if not self.l10n_sk_fund_assessment:
            return False
        try:
            return self._l10n_sk_checked_fund_assessment() or False
        except FundEvidenceError:
            return False

    def _l10n_sk_checked_fund_assessment(self):
        self.ensure_one()
        evidence = self.l10n_sk_fund_assessment
        if not evidence or evidence.get("schema") != 1 or not evidence.get("complete"):
            raise FundEvidenceError(
                _(
                    "Recalculate the unconfirmed payslip to record its payroll fund bases."
                )
            )
        if (
            evidence.get("identity") != self._l10n_sk_fund_identity()
            or evidence.get("salary") != self._l10n_sk_fund_salary_facts()
        ):
            raise FundEvidenceError(
                _("The recorded payroll fund bases no longer match the payslip.")
            )
        try:
            records = index_assessments(evidence["records"])
        except (ValueError, KeyError) as error:
            raise FundEvidenceError(
                _("The recorded payroll fund bases are invalid.")
            ) from error
        return list(records.values())
