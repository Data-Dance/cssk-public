"""Engine-neutral fund evidence; no payroll engine is imported here.

Each bridge owns the JSON/storage field ``l10n_sk_fund_assessment``, inherits
this mixin alongside its native hr.payslip and supplies
_l10n_sk_fund_identity and _l10n_sk_version (the contract version the payslip
is computed on); actual charged bases are supplied by salary rules, never
reconstructed here. The bridge also owns its capture hooks, its
compute_sheet wrapper, refund pairing and direction. Confirmation, source
locking and native child-row policies belong to the engine's lifecycle
adapter, not to this abstract protocol.
"""

