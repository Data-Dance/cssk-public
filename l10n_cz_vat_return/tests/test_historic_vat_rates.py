from odoo.addons.account.tests.common import AccountTestInvoicingCommon
from odoo.tests import tagged


@tagged("post_install", "-at_install")
class TestCzHistoricVatRates(AccountTestInvoicingCommon):
    """The Czech historical rates.

    The Czech form is *not* rate-agnostic the way the Slovak one is: DPHDP3
    separates the standard rate (lines 01/02, input 40) from the reduced one
    (03/04, input 41). What it does not distinguish is *which* reduced rate --
    15 % and the second-reduced 10 % both reported on 03/04 while they
    coexisted. So cloning is correct precisely because each historical rate is
    cloned from the family it belonged to, which is what these tests pin.

    The chart is loaded by the test rather than assumed to be in the database,
    which also exercises the chart-load hook: the rates below are generated by
    ``_load`` during ``setUpClass``, not by an explicit call.
    """

    chart_template = "cz"

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.company = cls.env.company
        cls.Tax = cls.env["account.tax"].with_context(active_test=False)

    def _historic(self, rate=None):
        domain = [
            ("company_id", "=", self.company.id),
            ("cssk_historic_valid_from", "!=", False),
        ]
        if rate is not None:
            domain.append(("amount", "=", rate))
        return self.Tax.search(domain)

    def _current(self, rate):
        return self.Tax.search([
            ("company_id", "=", self.company.id), ("amount", "=", rate),
            ("cssk_historic_valid_from", "=", False),
        ])

    def _settle(self):
        """Generate once, so the set of source taxes is not still moving.

        The accounting test fixture creates a few taxes of its own AFTER the
        chart is loaded, and therefore after the chart-load hook has run. Those
        legitimately have no historical twin yet, so a count or an idempotency
        check taken straight from ``setUpClass`` would be measuring the fixture
        rather than this module. Settling first is what makes the assertions
        about the generator.
        """
        return self.company._cssk_create_historic_vat_taxes()


    def test_loading_the_chart_generates_them(self):
        """Nobody has to remember to ask.

        A migration project's companies are created *after* the modules are
        installed, so a post-install hook alone would have missed exactly the
        companies the feature exists for.
        """
        self.assertTrue(
            self._historic(),
            "loading the Czech chart should have generated the historical "
            "rates without an explicit call",
        )

    def test_each_rate_is_cloned_from_the_family_it_belonged_to(self):
        """The rule the whole design rests on for CZ.

        20 % was a standard rate and must report on lines 01/02; 15 % was a
        reduced rate and must report on 03/04. Cloning 15 % from the 21 %
        family would file every 2013-2023 reduced supply as a standard one —
        the amount right and the return wrong, which is the failure nobody
        notices until the tax office does.
        """
        self._settle()
        for rate, expected_source in ((20.0, 21.0), (19.0, 21.0),
                                      (15.0, 12.0), (14.0, 12.0),
                                      (10.0, 12.0), (9.0, 12.0), (5.0, 12.0)):
            taxes = self._historic(rate)
            self.assertTrue(taxes, "no %g%% taxes were generated" % rate)
            self.assertEqual(
                set(taxes.mapped("cssk_historic_source_tax_id.amount")),
                {expected_source},
                "%g%% must be cloned from the %g%% family, because that is "
                "what decides whether it reports as standard or reduced"
                % (rate, expected_source),
            )

    def test_the_whole_family_is_generated_not_just_the_plain_rate(self):
        """A rate is not one tax — the CZ chart has EU, EX, RC and ND variants."""
        self._settle()
        current = self._current(12.0)
        self.assertTrue(current, "the 12 % family must exist to be cloned from")
        self.assertEqual(
            len(self._historic(15.0)), len(current),
            "every current reduced-rate tax needs a 15 % twin",
        )
        self.assertIn(
            "15% RC", set(self._historic(15.0).mapped("name")),
            "§ 92a domestic reverse charge",
        )

    def test_a_historic_rate_is_archived(self):
        """It must exist without appearing anywhere somebody raises a document."""
        historic = self._historic()
        self.assertTrue(historic)
        self.assertFalse(any(historic.mapped("active")))
        self.assertFalse(
            self.env["account.tax"].search([("id", "in", historic.ids)]),
            "an ordinary search must not return an archived rate",
        )

    def test_the_clone_keeps_the_tags_that_make_it_report(self):
        """A rate with no tags computes a number and reports it nowhere."""
        self._settle()
        checked = 0
        for tax in self._historic():
            source = tax.cssk_historic_source_tax_id
            self.assertTrue(source, "a generated rate must name what it came from")
            for field in ("invoice_repartition_line_ids",
                          "refund_repartition_line_ids"):
                mine = tax[field].filtered(lambda r: r.repartition_type == "tax")
                theirs = source[field].filtered(
                    lambda r: r.repartition_type == "tax")
                self.assertEqual(
                    [sorted(x.tag_ids.mapped("name")) for x in mine],
                    [sorted(x.tag_ids.mapped("name")) for x in theirs],
                    "%s does not carry its source's tags" % tax.name,
                )
                self.assertEqual(
                    mine.mapped("factor_percent"),
                    theirs.mapped("factor_percent"),
                    "%s changed the repartition split — on a §92a reverse "
                    "charge that is the +100/-100 pair" % tax.name,
                )
            checked += 1
        self.assertTrue(checked, "nothing was actually checked")

    def test_running_twice_creates_nothing_and_clones_no_clones(self):
        """Idempotent: this runs on every module upgrade and every chart load."""
        self._settle()
        before = self._historic()
        self._settle()
        after = self._historic()
        self.assertEqual(set(before.ids), set(after.ids))
        self.assertFalse(
            after.filtered(
                lambda t: t.cssk_historic_source_tax_id.cssk_historic_valid_from
            ),
            "a historical rate was cloned from another historical rate",
        )

    def test_a_hand_made_rate_is_adopted_rather_than_duplicated(self):
        """The state the Czech reference company was actually in.

        Six rates at 15 % and 10 % created ad hoc for one import, active and
        unmarked. Two identical-looking taxes would be worse than none: the
        mapping picks one and the reports read the other.
        """
        self._historic().unlink()
        self.assertFalse(self._historic(), "starting from no generated rates")
        source = self._current(12.0).filtered(
            lambda t: t.type_tax_use == "purchase" and t.name == "12% G"
        )[:1]
        self.assertTrue(source, "expected a 12% G purchase tax")
        handmade = source.copy({"name": "15% G", "amount": 15.0})
        self.assertTrue(handmade.active)

        self.company._cssk_create_historic_vat_taxes()

        same = self.Tax.search([
            ("company_id", "=", self.company.id), ("name", "=", "15% G"),
            ("type_tax_use", "=", "purchase"),
        ])
        self.assertEqual(
            same, handmade,
            "the hand-made rate should have been adopted, leaving exactly one",
        )
        self.assertFalse(handmade.active)
        self.assertEqual(handmade.cssk_historic_valid_from.year, 2013)
        self.assertEqual(handmade.cssk_historic_valid_to.year, 2023)
        self.assertEqual(handmade.cssk_historic_source_tax_id, source)

    # -- the tax-replacement links ----------------------------------------

    def test_a_vintage_is_replaced_by_its_own_vintage(self):
        """``copy()`` copies the replacement link, and it is ONE relation.

        ``original_tax_ids`` ("Replaces") and ``replacing_tax_ids``
        ("Replaced by") are the same ``account_tax_alternatives`` rows read
        from either end, and both are copied. A clone therefore arrived
        claiming the taxes in force TODAY as its replacements — measured on
        this chart before the repair::

            20% G  replaced_by  21% EX G, 21% EX S, 0% EX G.Custom,
                                20% EX G, 20% EX S, 19% EX G, 19% EX S

        Seven destinations for one rate across three vintages. What that buys
        is a 2011 extra-Community purchase entered at 20 % and self-assessed
        by the fiscal position at 21 %, which is the restatement this whole
        feature exists to prevent.
        """
        for rate in (20.0, 15.0):
            for tax in self._historic(rate):
                for field in ("original_tax_ids", "replacing_tax_ids"):
                    wrong = tax[field].filtered(
                        lambda t: t.amount and t.amount != rate)
                    self.assertFalse(
                        wrong,
                        "%s (%g %%) %s a rate of its own vintage only, not %s"
                        % (tax.name, rate, field,
                           [(t.name, t.amount) for t in wrong]))

    def test_a_rate_free_counterpart_is_kept_rather_than_dropped(self):
        """A zero-rated destination has no vintage, so it is left alone.

        ``0% EX G.Custom`` is wired by the chart as a replacement for every
        domestic purchase tax. Re-pointing cannot improve that link — there is
        no 20 % version of a 0 % tax — and dropping it would remove a mapping
        on a guess, so it survives. Pinned because the obvious
        "rebuild the list from the clones" implementation silently loses it.
        """
        custom = self.env["account.chart.template"].ref(
            "l10n_cz_import_goods_tax_authority", raise_if_not_found=False)
        if not custom:
            self.skipTest("this chart ships no ř. 42 customs tax")
        kept = self._historic(20.0).filtered(
            lambda t: custom in t.replacing_tax_ids)
        self.assertTrue(
            kept,
            "the 20 %% rates lost their rate-free replacements; "
            "_cssk_revintage_replacements must keep what it cannot re-point")

    def test_re_running_the_generator_does_not_accumulate_links(self):
        """Seven vintages each see the previous six.

        So the pass has to read the SOURCE's current-rate links, not whatever
        the source has accumulated — otherwise every run adds every vintage to
        every vintage, and the growth is silent.
        """
        # Run it ONCE first. The test framework creates its own copies of the
        # domestic taxes after the chart loaded, so the first re-run legitimately
        # gives those a vintage twin and the links legitimately grow. What must
        # not grow is a run that found nothing new.
        self.company._cssk_create_historic_vat_taxes()
        before = {
            tax: set(tax.replacing_tax_ids.ids)
            for tax in self._historic()
        }
        self.company._cssk_create_historic_vat_taxes()
        grown = {
            tax.name: sorted(set(tax.replacing_tax_ids.ids) - ids)
            for tax, ids in before.items()
            if set(tax.replacing_tax_ids.ids) - ids
        }
        self.assertFalse(grown, "links accumulated on a re-run: %s" % grown)

    def test_a_hand_made_rate_keeps_its_own_replacement_links(self):
        """An ADOPTED vintage is swapped link by link, never rewritten.

        Both of these fields are the same ``account_tax_alternatives`` table
        read from opposite ends, so an exact-set write on a rate somebody
        created by hand discards their mapping twice over. The generated
        clones are rewritten outright — their inherited list is the current
        rate's and means nothing for a vintage — but an adopted one is not.
        Raised by a GPT-5.3-Codex review.
        """
        twenty = self._historic(20.0).filtered(
            lambda t: t.type_tax_use == "purchase")[:1]
        self.assertTrue(twenty)
        unrelated = self.env["account.chart.template"].ref(
            "l10n_cz_not_subject_vat")
        twenty.original_tax_ids = [(4, unrelated.id)]
        # Force the adoption path: the tax already carries the generated name.
        self.company._cssk_create_historic_vat_taxes()
        self.assertIn(
            unrelated, twenty.original_tax_ids,
            "re-vintaging discarded a link that was not the generator's to "
            "remove")
