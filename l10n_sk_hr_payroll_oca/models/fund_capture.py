"""Capture actual rule values without changing native payroll arithmetic."""

from copy import deepcopy
from decimal import Decimal

from odoo import _, api, fields, models
from odoo.exceptions import UserError

from odoo.addons.l10n_sk_hr_payroll_base.fund_assessment import (
    fund_assessment,
    index_assessments,
)
from odoo.addons.l10n_sk_hr_payroll_base.fund_codes import SOCIAL_FUNDS
from odoo.addons.l10n_sk_hr_payroll_base.models.payslip_fund_mixin import (
    FundEvidenceError,
)


class _FundCapture:
    """An in-process context capability; JSON/RPC cannot construct this object."""

    def __init__(self, supported):
        self.supported = set(supported)
        self.rows = {}


class FundCapturePayslip(models.Model):
    _name = "hr.payslip"
    _inherit = ["hr.payslip", "l10n.sk.payslip.fund.mixin"]

    l10n_sk_fund_assessment = fields.Json(
        string="Recorded payroll fund bases",
        readonly=True,
        copy=False,
    )

    @api.model_create_multi
    def create(self, values_list):
        if "default_l10n_sk_fund_assessment" in self.env.context or any(
            "l10n_sk_fund_assessment" in values for values in values_list
        ):
            raise UserError(_("Fund evidence is generated by payroll calculation."))
        return super().create(values_list)

    def write(self, values):
        if "l10n_sk_fund_assessment" in values:
            raise UserError(_("Fund evidence is generated by payroll calculation."))
        return super().write(values)

    def _l10n_sk_can_record_funds(self):
        """Unsupported metadata must never prevent the native calculation."""
        self.ensure_one()
        if (
            not self.date_from
            or not self.date_to
            or (self.date_from.year, self.date_from.month)
            != (self.date_to.year, self.date_to.month)
        ):
            return False
        version = self.contract_id or self._get_employee_contracts()
        return bool(
            len(version) == 1
            and version.employee_id == self.employee_id
            and version.company_id == self.company_id
        )

    def _l10n_sk_is_recording_funds(self):
        self.ensure_one()
        capture = self.env.context.get("_l10n_sk_fund_capture")
        return isinstance(capture, _FundCapture) and self.id in capture.supported

    def _l10n_sk_fund_identity(self):
        self.ensure_one()
        return {
            "company": self.company_id.id,
            "employee": self.employee_id.id,
            "contract": self.contract_id.id,
            "from": str(self.date_from),
            "to": str(self.date_to),
            "structure": self.struct_id.id,
            "credit_note": self.credit_note,
        }

    def _l10n_sk_fund_salary_facts(self):
        self.ensure_one()
        return sorted(
            [
                [
                    line.code,
                    line.salary_rule_id.id,
                    line.amount,
                    line.quantity,
                    line.rate,
                    line.total,
                ]
                for line in self.line_ids
            ]
        )

    def _l10n_sk_fund_profile(self):
        """Store the statutory profile once; never copy restricted birth numbers."""
        version = self._l10n_sk_version()
        return {
            "version": version.id,
            "agreement": version.l10n_sk_employment_form(),
            "pension": version.l10n_sk_pension_status(),
            "regular": version.l10n_sk_income_is_regular(),
            "oop": version.l10n_sk_agreement_oop,
            "guarantee_exempt": version.l10n_sk_guarantee_exempt,
        }

    def _get_baselocaldict(self, contracts):
        result = super()._get_baselocaldict(contracts)
        if self._l10n_sk_is_recording_funds():
            result["l10n_sk_fund_records"] = {}
            result["l10n_sk_fund_missing"] = False
        return result

    def _compute_payslip_line(self, rule, localdict, lines_dict):
        localdict.pop("l10n_sk_fund_record", None)
        result, lines = super()._compute_payslip_line(rule, localdict, lines_dict)
        if not self._l10n_sk_is_recording_funds():
            return result, lines
        records = result.get("l10n_sk_fund_records")
        if records is None:
            return result, lines
        record = result.pop("l10n_sk_fund_record", None)
        if record is None:
            if rule.code in SOCIAL_FUNDS or rule.code in {"HEALTH", "HEALTHEMPLOYER"}:
                result["l10n_sk_fund_missing"] = True
            return result, lines
        try:
            normalized = next(iter(index_assessments([record]).values()))
        except ValueError:
            result["l10n_sk_fund_missing"] = True
            return result, lines
        native_charge = result["result_rules"].dict[rule.code].total
        if normalized["side"] == "employee":
            native_charge = -native_charge
        if self.company_id.currency_id.compare_amounts(
            float(normalized["amount"]), native_charge
        ):
            # A customised rate/quantity can invalidate the optional metadata
            # while the native calculation remains valid.
            result["l10n_sk_fund_missing"] = True
            return result, lines
        key = normalized["fund"], normalized["side"]
        if key in records:
            result["l10n_sk_fund_missing"] = True
        records[key] = normalized
        return result, lines

    def localdict_hook(self, localdict):
        result = super().localdict_hook(localdict)
        if not self._l10n_sk_is_recording_funds():
            return result
        capture = self.env.context["_l10n_sk_fund_capture"]
        records = result.get("l10n_sk_fund_records")
        if not records or result.get("l10n_sk_fund_missing"):
            capture.rows[self.id] = False
            return result
        employee = records.get(("health", "employee"))
        rules = result["result_rules"].dict
        if employee and "HEALTHDOPLATOK" in rules:
            # The native separate minimum rule adds a charge, not another base.
            topup = -rules["HEALTHDOPLATOK"].total
            records[("health", "employee")] = fund_assessment(
                fund="health",
                side="employee",
                base=employee["base"],
                rate=employee["rate"],
                amount=Decimal(employee["amount"]) + Decimal(str(topup)),
                facts=dict(employee["facts"], topup=topup),
            )
        capture.rows[self.id] = list(records.values())
        return result

    def compute_sheet(self):
        capture = _FundCapture(
            self.filtered(lambda slip: slip._l10n_sk_can_record_funds()).ids
        )
        recording = self.with_context(_l10n_sk_fund_capture=capture)
        with self.env.cr.savepoint():
            super(FundCapturePayslip, recording).write(
                {"l10n_sk_fund_assessment": False}
            )
            result = super(FundCapturePayslip, recording).compute_sheet()
            for slip in recording:
                rows = capture.rows.get(slip.id)
                if rows:
                    evidence = {
                        "schema": 1,
                        "complete": True,
                        "records": rows,
                        "identity": slip._l10n_sk_fund_identity(),
                        "salary": slip._l10n_sk_fund_salary_facts(),
                        "profile": slip._l10n_sk_fund_profile(),
                    }
                    super(FundCapturePayslip, slip).write(
                        {"l10n_sk_fund_assessment": evidence}
                    )
            return result

    def _l10n_sk_refund_original(self):
        self.ensure_one()
        if not self.credit_note:
            return self.browse()
        original = self.search([("refunded_id", "=", self.id)])
        if len(original) != 1 or original.state not in {"done", "cancel"}:
            return self.browse()
        names = (
            "company_id",
            "employee_id",
            "contract_id",
            "date_from",
            "date_to",
            "struct_id",
        )
        if any(self[name] != original[name] for name in names) or (
            self._l10n_sk_fund_salary_facts() != original._l10n_sk_fund_salary_facts()
        ):
            return self.browse()
        return original

    def _cssk_recorded_fund_bases(self):
        self.ensure_one()
        self.check_access("read")
        original = self._l10n_sk_refund_original()
        if original:
            return [
                dict(row, facts=dict(row["facts"], refund_of_payslip=original.id))
                for row in deepcopy(original._cssk_recorded_fund_bases() or [])
            ] or False
        if not self.l10n_sk_fund_assessment:
            return False
        try:
            return self._l10n_sk_checked_fund_assessment() or False
        except FundEvidenceError:
            return False

    def _cssk_effective_fund_payslips(self):
        removed = self.browse()
        for refund in self.filtered("credit_note"):
            original = refund._l10n_sk_refund_original()
            if original and original in self:
                removed |= original | refund
        return self - removed

    def _cssk_fund_record_direction(self):
        """OCA uses positive copied lines and a native credit-note direction."""
        self.ensure_one()
        return -1 if self.credit_note else 1
