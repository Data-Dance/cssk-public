"""Retain the health facts produced with a payslip, not today's HR card."""

from datetime import timedelta

from odoo import _, api, fields, models
from odoo.exceptions import UserError


class HealthAssessmentEmployee(models.Model):
    _inherit = "hr.employee"

    l10n_sk_health_minimum_opt_out = fields.Boolean(
        related="version_id.l10n_sk_health_minimum_opt_out",
        inherited=True,
        readonly=False,
        groups="payroll.group_payroll_user",
    )
    l10n_sk_health_minimum_evidence = fields.Char(
        related="version_id.l10n_sk_health_minimum_evidence",
        inherited=True,
        readonly=False,
        groups="payroll.group_payroll_user",
    )


class HealthAssessmentPayslip(models.Model):
    _inherit = "hr.payslip"

    l10n_sk_health_assessment_snapshot = fields.Json(
        string="Health assessment evidence",
        readonly=True,
        copy=False,
        help="Generated with payroll. Used by the health statement without "
        "reclassifying historical income from the current employee card.",
    )

    @api.model_create_multi
    def create(self, vals_list):
        if "default_l10n_sk_health_assessment_snapshot" in self.env.context or any(
            "l10n_sk_health_assessment_snapshot" in vals for vals in vals_list
        ):
            raise UserError(_("Health assessment evidence is generated by payroll."))
        return super().create(vals_list)

    def write(self, vals):
        if "l10n_sk_health_assessment_snapshot" in vals:
            raise UserError(_("Health assessment evidence is generated by payroll."))
        return super().write(vals)

    def _l10n_sk_health_day_facts(self, version):
        """Health calendar days, independent of scheduled working hours.

        PN/benefit and unpaid/family-leave calendar spans are unioned before
        counting. A legacy manual PN worked-day row alone is not evidence of
        calendar days: the snapshot retains that gap instead of guessing.
        """
        self.ensure_one()
        calendar = version._l10n_sk_health_calendar_context(self.date_from)
        if calendar:
            return dict(calendar, reason=False)
        if (
            version.l10n_sk_agreement_type in ("dopc", "dovp", "dobps")
            and not version.l10n_sk_health_exempt
        ):
            # Insured agreements use registered work days (2D), including
            # the statutory rest-day/fallback rules. Contract duration alone
            # is not evidence of those days. A registration/day-source
            # adapter must supply them before a text statement is generated.
            return {"insured_days": None, "reason": "agreement_requires_2d_day_source"}
        start = max(
            self.date_from, version.sudo().contract_date_start or self.date_from
        )
        end = min(self.date_to, version.sudo().contract_date_end or self.date_to)
        employed = max(0, (end - start).days + 1)
        excluded, pn = set(), set()
        if "hr.leave" in self.env and start <= end:
            leaves = self.env["hr.leave"].search(
                [
                    ("employee_id", "=", self.employee_id.id),
                    ("state", "=", "validate"),
                    ("request_date_from", "<=", end),
                    ("request_date_to", ">=", start),
                ]
            )
            codes = {"PN", "OCR", "MATERSKA", "OTCOVSKA", "RODICOVSKA", "NEPLATENE"}
            for leave in leaves:
                code = leave.holiday_status_id.l10n_sk_payroll_code
                if code not in codes:
                    continue
                lo, hi = (
                    max(start, leave.request_date_from),
                    min(end, leave.request_date_to),
                )
                days = {lo + timedelta(days=n) for n in range((hi - lo).days + 1)}
                excluded |= days
                if code == "PN":
                    pn |= days
        manual = self.input_line_ids.filtered(lambda row: row.code == "PN_DAYS")
        manual_days = sum(manual.mapped("amount"))
        if manual:
            if manual_days != int(manual_days) or not 0 <= manual_days <= employed:
                return {
                    "insured_days": None,
                    "reason": "invalid_manual_pn_calendar_days",
                }
            if pn and manual_days != len(pn):
                return {"insured_days": None, "reason": "pn_calendar_sources_disagree"}
            if not pn:
                # Without dates, an overlap with another excluded period
                # cannot be distinguished from two separate absences.
                if excluded and manual_days:
                    return {"insured_days": None, "reason": "undated_pn_overlap"}
                return {
                    "insured_days": employed - len(excluded) - int(manual_days),
                    "reason": False,
                }
        elif not pn and self.worked_days_line_ids.filtered(
            lambda row: row.code == "PN"
        ):
            return {"insured_days": None, "reason": "pn_workdays_are_not_calendar_days"}
        return {"insured_days": employed - len(excluded), "reason": False}

    def _l10n_sk_build_health_assessment(self, version):
        self.ensure_one()
        premium_codes = (
            "GROSS",
            "HEALTH",
            "HEALTHEMPLOYER",
            "HEALTHDOPLATOK",
            "HEALTH_DOPLATOK",
        )
        salary = {
            code: sum(
                self.line_ids.filtered(lambda line: line.code == code).mapped("total")
            )
            for code in premium_codes
        }
        gross = salary["GROSS"]
        disabled = version.l10n_sk_health_is_disabled(self.date_from)
        suffix = "_ztp" if disabled else ""
        ee_rate = self.rule_parameter("l10n_sk_health_rate_employee" + suffix)
        facts = version.l10n_sk_health_employee_assessment(
            gross,
            ee_rate,
            self.date_from,
            self.rule_parameter("l10n_sk_health_oop_max"),
            self.rule_parameter("l10n_sk_health_oop_phaseout_end"),
        )
        facts.update(
            {
                "version": 1,
                "company_id": self.company_id.id,
                "employee_id": self.employee_id.id,
                "contract_id": version.id,
                "date_from": str(self.date_from),
                "date_to": str(self.date_to),
                "disabled": disabled,
                "agreement_type": version.l10n_sk_agreement_type,
                "pension_type": version.l10n_sk_pension_type,
                "minimum_opt_out": int(version.l10n_sk_health_minimum_is_opted_out()),
                "minimum_evidence": version.l10n_sk_health_minimum_evidence or False,
                "rate_employer": self.rule_parameter(
                    "l10n_sk_health_rate_employer" + suffix
                ),
                "employer": salary["HEALTHEMPLOYER"],
                "topup": -sum(
                    salary[code] for code in ("HEALTHDOPLATOK", "HEALTH_DOPLATOK")
                ),
                "birth_number": "".join(
                    char
                    for char in (self.employee_id.identification_id or "")
                    if char.isdigit()
                ),
                "insurer": (
                    self.employee_id._l10n_sk_health_insurer()
                    if hasattr(self.employee_id, "_l10n_sk_health_insurer")
                    else False
                ),
                "salary": salary,
            }
        )
        facts.update(self._l10n_sk_health_day_facts(version))
        if round(facts["employee"] + salary["HEALTH"], 2):
            raise UserError(
                _(
                    "The health assessment base disagrees with the computed employee premium."
                )
            )
        return facts

    def compute_sheet(self):
        confirmed_ids = set(
            self.filtered(lambda slip: slip.state in ("done", "paid", "validated")).ids
        )
        for slip in self:
            version = slip._l10n_sk_version()
            if len(version) == 1 and slip.company_id.country_id.code == "SK":
                version.l10n_sk_health_minimum_is_opted_out()
        result = super().compute_sheet()
        for slip in self:
            version = slip._l10n_sk_version()
            if len(version) != 1 or slip.company_id.country_id.code != "SK":
                continue
            # A confirmed source is never silently rewritten by recalculation.
            # Existing accounting/posted-payslip guards retain their own scope.
            if slip.id in confirmed_ids or slip.state in ("done", "paid", "validated"):
                continue
            facts = slip._l10n_sk_build_health_assessment(version)
            super(HealthAssessmentPayslip, slip).write(
                {"l10n_sk_health_assessment_snapshot": facts}
            )
        return result

    def _l10n_sk_health_assessment_facts(self):
        self.ensure_one()
        facts = self.l10n_sk_health_assessment_snapshot
        identity = {
            "company_id": self.company_id.id,
            "employee_id": self.employee_id.id,
            "date_from": str(self.date_from),
            "date_to": str(self.date_to),
        }
        if (
            not facts
            or facts.get("version") != 1
            or any(facts.get(key) != value for key, value in identity.items())
        ):
            raise UserError(
                _(
                    "This payslip has no matching retained health assessment. Review its original payroll sources."
                )
            )
        if self.contract_id and self.contract_id.id != facts.get("contract_id"):
            raise UserError(
                _("The payslip contract differs from its retained health assessment.")
            )
        for code, amount in facts["salary"].items():
            current = sum(
                self.line_ids.filtered(lambda line: line.code == code).mapped("total")
            )
            if current != amount:
                raise UserError(
                    _(
                        "A health payroll amount changed after the retained assessment was generated."
                    )
                )
        if facts["insured_days"] is None:
            if facts.get("reason") == "agreement_requires_2d_day_source":
                raise UserError(
                    _(
                        "Review the registered health-insurance days of this work agreement before generating the statement."
                    )
                )
            raise UserError(
                _(
                    "Review the calendar dates of sickness and other absences before generating the health statement."
                )
            )
        return dict(facts)

    def action_payslip_done(self):
        newly_confirmed = self.filtered(
            lambda slip: slip.state not in ("done", "paid", "validated")
        )
        with self.env.cr.savepoint():
            result = super().action_payslip_done()
            for slip in newly_confirmed:
                original = slip.l10n_sk_health_assessment_snapshot
                if not original:
                    # Legacy/manual payroll has no adopted evidence. It does
                    # not gain a fabricated source; TXT generation will ask
                    # for review of the original payroll instead.
                    continue
                version = slip._l10n_sk_version()
                if len(
                    version
                ) != 1 or original != slip._l10n_sk_build_health_assessment(version):
                    raise UserError(
                        _(
                            "Health assessment sources changed. Recalculate the unposted payslip before confirmation."
                        )
                    )
            return result
