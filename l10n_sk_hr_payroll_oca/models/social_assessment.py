"""Retain the bases used for regular monthly social-insurance declarations."""

from odoo import _, api, fields, models
from odoo.exceptions import UserError
from odoo.addons.l10n_sk_hr_payroll_base.social_assessment import social_premium


FUND_FIELDS = {
    "SICK": "vzZecNp",
    "PENSION": "vzZecSp",
    "DISABILITY": "vzZecIp",
    "UNEMPLOYMENT": "vzZecPvn",
    "SICKEMPLOYER": "vzNp",
    "PENSIONEMPLOYER": "vzSp",
    "DISABILITYEMPLOYER": "vzIp",
    "UNEMPLOYMENTEMPLOYER": "vzPvn",
    "SHORTTIMEEMPLOYER": "vzPfp",
    "GUARANTEEEMPLOYER": "vzGp",
    "ACCIDENT": "vzUp",
    "RESERVEFUNDEMPLOYER": "vzRfs",
}
RATE_PARAMETERS = {
    "SICK": "l10n_sk_social_sickness_ee",
    "PENSION": "l10n_sk_social_pension_ee",
    "DISABILITY": "l10n_sk_social_disability_ee",
    "UNEMPLOYMENT": "l10n_sk_social_unemployment_ee",
    "SICKEMPLOYER": "l10n_sk_social_sickness_er",
    "PENSIONEMPLOYER": "l10n_sk_social_pension_er",
    "DISABILITYEMPLOYER": "l10n_sk_social_disability_er",
    "UNEMPLOYMENTEMPLOYER": "l10n_sk_social_unemployment_er",
    "SHORTTIMEEMPLOYER": "l10n_sk_social_shorttime_er",
    "GUARANTEEEMPLOYER": "l10n_sk_social_guarantee_er",
    "ACCIDENT": "l10n_sk_social_accident_er",
    "RESERVEFUNDEMPLOYER": "l10n_sk_social_reserve_er",
}


class Payslip(models.Model):
    _inherit = "hr.payslip"

    l10n_sk_social_assessment = fields.Json(
        string="Retained social-insurance bases", readonly=True, copy=False
    )
    l10n_sk_social_confirmed_at = fields.Datetime(
        string="Social-insurance source confirmed at", readonly=True, copy=False
    )

    @api.model_create_multi
    def create(self, values_list):
        generated = {"l10n_sk_social_assessment", "l10n_sk_social_confirmed_at"}
        if any("default_" + name in self.env.context for name in generated) or any(
            generated & values.keys() for values in values_list
        ):
            raise UserError(
                _("Social-insurance evidence is generated by payroll calculation.")
            )
        return super().create(values_list)

    def write(self, values):
        if {"l10n_sk_social_assessment", "l10n_sk_social_confirmed_at"} & values.keys():
            raise UserError(
                _("Social-insurance evidence is generated by payroll calculation.")
            )
        confirmed = self.filtered("l10n_sk_social_confirmed_at")
        immutable = {
            "employee_id",
            "company_id",
            "contract_id",
            "date_from",
            "date_to",
            "struct_id",
            "credit_note",
            "line_ids",
            "worked_days_line_ids",
            "input_line_ids",
        }
        if confirmed and immutable & values.keys():
            raise UserError(
                _(
                    "Retain confirmed social-insurance sources; use a payroll correction."
                )
            )
        if "state" in values and any(
            values["state"] != slip.state and values["state"] != "cancel"
            for slip in confirmed
        ):
            raise UserError(
                _(
                    "Retain confirmed social-insurance sources; use a payroll correction."
                )
            )
        if values.get("state") == "done":
            pending = self.filtered(
                lambda slip: not slip.l10n_sk_social_confirmed_at
                and slip._l10n_sk_social_assessment_required()
            )
            if pending:
                pending._l10n_sk_lock_social_payslips()
                for slip in pending:
                    slip._l10n_sk_checked_social_assessment(current=True)
                super(Payslip, pending).write(
                    dict(values, l10n_sk_social_confirmed_at=fields.Datetime.now())
                )
                remainder = self - pending
                return super(Payslip, remainder).write(values) if remainder else True
        return super().write(values)

    def _l10n_sk_social_assessment_required(self):
        """Allocation/correction adapters can provide a different source policy."""
        self.ensure_one()
        version = self._l10n_sk_version()
        return bool(
            version
            and self.struct_id.country_id.code == "SK"
            and version.l10n_sk_income_is_regular()
            and not self.credit_note
        )

    def unlink(self):
        if any(slip.l10n_sk_social_confirmed_at for slip in self):
            raise UserError(
                _(
                    "Retain confirmed social-insurance sources; use a payroll correction."
                )
            )
        return super().unlink()

    def _l10n_sk_social_salary_facts(self):
        return sorted(
            [
                [
                    line.code,
                    line.salary_rule_id.id,
                    line.amount,
                    line.quantity,
                    line.rate,
                    line.total,
                ]
                for line in self.line_ids
                if line.code in set(FUND_FIELDS) | {"GROSS"}
            ]
        )

    def _l10n_sk_social_source_facts(self):
        self.ensure_one()
        version = self._l10n_sk_version()
        if (
            version.employee_id != self.employee_id
            or version.company_id != self.company_id
        ):
            raise UserError(
                _("Use the employee and company version for social insurance.")
            )
        versions = (
            self.env["hr.version"]
            .search(
                [
                    ("employee_id", "=", self.employee_id.id),
                    ("company_id", "=", self.company_id.id),
                    ("contract_date_start", "=", version.contract_date_start),
                    ("date_version", "<=", self.date_to),
                ],
                order="date_version,id",
            )
            .filtered(
                lambda item: item.date_start <= self.date_to
                and (not item.date_end or item.date_end >= self.date_from)
            )
        )
        rows = [
            {
                "id": item.id,
                "date": str(item.date_version),
                "wage": item.wage,
                "hourly": item.l10n_sk_hourly_wage,
                "profile": [
                    item.l10n_sk_employment_form(),
                    item.l10n_sk_income_is_regular(),
                    item.l10n_sk_pension_status(),
                    item.l10n_sk_agreement_oop,
                    item.l10n_sk_guarantee_exempt,
                ],
            }
            for item in versions
        ]
        if any(row["profile"] != rows[0]["profile"] for row in rows):
            raise UserError(
                _(
                    "Review a changed social-insurance profile within the month before monthly consolidation."
                )
            )
        rates = {
            code: self.rule_parameter(parameter)
            for code, parameter in RATE_PARAMETERS.items()
        }
        if not version.l10n_sk_applies("SHORTTIME_CONTRIBUTION"):
            rates["UNEMPLOYMENTEMPLOYER"] = self.rule_parameter(
                "l10n_sk_social_unemployment_er_no_shorttime"
            )
        return {
            "company": self.company_id.id,
            "employee": self.employee_id.id,
            "version": version.id,
            "from": str(self.date_from),
            "to": str(self.date_to),
            "employment_from": str(version.contract_date_start),
            "employment_to": str(version.contract_date_end)
            if version.contract_date_end
            else False,
            "agreement": version.l10n_sk_employment_form(),
            "regular": version.l10n_sk_income_is_regular(),
            "pension": version.l10n_sk_pension_status(),
            "oop": version.l10n_sk_agreement_oop,
            "guarantee_exempt": version.l10n_sk_guarantee_exempt,
            "wage": version.wage,
            "hourly": version.l10n_sk_hourly_wage,
            "cap": self.rule_parameter("l10n_sk_monthly_taxable_max"),
            "deduction": self.rule_parameter("l10n_sk_dohoda_oop"),
            "rates": rates,
            "structure": self.struct_id.id,
            "credit_note": self.credit_note,
            "dated_versions": rows,
            "inputs": sorted(
                [row.code, row.contract_id.id, row.amount, row.sequence]
                for row in self.input_line_ids
            ),
            "worked_days": sorted(
                [row.code, row.contract_id.id, row.number_of_days, row.number_of_hours]
                for row in self.worked_days_line_ids
            ),
        }

    def _l10n_sk_build_social_assessment(self):
        self.ensure_one()
        version = self._l10n_sk_version()
        gross = self.get_salary_line_total("GROSS")
        if gross < 0:
            return False
        facts = self._l10n_sk_social_source_facts()
        if gross and (
            (version.contract_date_start and version.contract_date_start > self.date_to)
            or (
                version.contract_date_end and version.contract_date_end < self.date_from
            )
        ):
            raise UserError(
                _(
                    "Use a reviewed historical income allocation for payment outside the employment period."
                )
            )
        lines = {line.code: line for line in self.line_ids if line.code in FUND_FIELDS}
        bases = {
            field: version.l10n_sk_social_fund_base(
                gross, code, facts["cap"], self.date_from, facts["deduction"]
            )
            if code in lines
            else 0.0
            for code, field in FUND_FIELDS.items()
        }
        for code, line in lines.items():
            expected = social_premium(bases[FUND_FIELDS[code]], facts["rates"][code])
            if code in {"SICK", "PENSION", "DISABILITY", "UNEMPLOYMENT"}:
                expected = -expected
            if round(line.total, 2) != expected:
                # An allocation/custom-rule adapter must retain its own exact
                # bases. Never back-calculate a base from a rounded premium.
                return False
        return {
            "policy": "social-funds-v1",
            "facts": facts,
            "bases": bases,
            "salary": self._l10n_sk_social_salary_facts(),
        }

    def compute_sheet(self):
        self._l10n_sk_lock_social_payslips()
        if any(
            slip.l10n_sk_social_confirmed_at
            or (
                slip.state == "done"
                and (
                    slip.l10n_sk_social_assessment
                    or slip._l10n_sk_social_assessment_required()
                )
            )
            for slip in self
        ):
            raise UserError(
                _(
                    "Retain confirmed payroll; use a payroll correction instead of recalculation."
                )
            )
        with self.env.cr.savepoint():
            for slip in self:
                if slip._l10n_sk_social_assessment_required():
                    slip._l10n_sk_social_source_facts()
            result = super().compute_sheet()
            for slip in self:
                evidence = (
                    slip._l10n_sk_build_social_assessment()
                    if slip._l10n_sk_social_assessment_required()
                    else False
                )
                super(Payslip, slip).write({"l10n_sk_social_assessment": evidence})
            return result

    def _l10n_sk_checked_social_assessment(self, current=False):
        self.ensure_one()
        evidence = self.l10n_sk_social_assessment
        if not evidence or evidence.get("policy") != "social-funds-v1":
            raise UserError(
                _(
                    "Review missing retained social-insurance bases before creating a new monthly declaration."
                )
            )
        facts = evidence["facts"]
        identity = {
            "company": self.company_id.id,
            "employee": self.employee_id.id,
            "version": self._l10n_sk_version().id,
            "from": str(self.date_from),
            "to": str(self.date_to),
        }
        if (
            any(facts.get(key) != value for key, value in identity.items())
            or evidence["salary"] != self._l10n_sk_social_salary_facts()
        ):
            raise UserError(
                _("The retained social-insurance bases no longer match the payslip.")
            )
        if current:
            self._l10n_sk_check_monthly_social_source()
        if current and evidence != self._l10n_sk_build_social_assessment():
            raise UserError(
                _(
                    "Social-insurance sources changed. Recalculate the unconfirmed payslip."
                )
            )
        return evidence

    def _l10n_sk_check_monthly_social_source(self):
        """Independent monthly calculations must not consume a cap/OOP twice.

        The employee epoch held by confirmation serializes competing payslips.
        Allocation/correction adapters retain a different cumulative source and
        opt out through _l10n_sk_social_assessment_required.
        """
        if not self._l10n_sk_social_assessment_required():
            return
        siblings = self._l10n_sk_monthly_social_sources()
        if any(slip._l10n_sk_social_assessment_required() for slip in siblings):
            raise UserError(
                _(
                    "Consolidate the employee's monthly remuneration before confirming another independent social-insurance calculation."
                )
            )

    def _l10n_sk_monthly_social_sources(self):
        """Current independent sources; correction adapters may filter replacements."""
        first = self.date_from.replace(day=1)
        last = fields.Date.end_of(self.date_to, "month")
        siblings = self.search(
            [
                ("id", "!=", self.id),
                ("employee_id", "=", self.employee_id.id),
                ("company_id", "=", self.company_id.id),
                ("state", "=", "done"),
                ("credit_note", "=", False),
                ("date_from", "<=", last),
                ("date_to", ">=", first),
            ]
        )

        def fully_refunded(slip):
            refund = slip.refunded_id
            return bool(
                refund
                and refund.state == "done"
                and refund.credit_note
                and refund.employee_id == slip.employee_id
                and refund.company_id == slip.company_id
                and refund.contract_id == slip.contract_id
                and refund.date_from == slip.date_from
                and refund.date_to == slip.date_to
                and refund._l10n_sk_social_salary_facts()
                == slip._l10n_sk_social_salary_facts()
            )

        return siblings.filtered(lambda slip: not fully_refunded(slip))

    def _l10n_sk_mvp_fund_bases(self):
        return self._l10n_sk_checked_social_assessment()["bases"]

    def _l10n_sk_social_relationship(self):
        if not self.l10n_sk_social_assessment:
            return False
        facts = self._l10n_sk_checked_social_assessment()["facts"]
        return facts["agreement"], facts["regular"]

    def _l10n_sk_mvp_source_facts(self):
        return self._l10n_sk_checked_social_assessment()["facts"]

    def action_payslip_done(self):
        with self.env.cr.savepoint():
            return self._l10n_sk_confirm_social_sheet()

    def _l10n_sk_confirm_social_sheet(self):
        self._l10n_sk_lock_social_payslips()
        covered = self.filtered(
            lambda slip: slip.l10n_sk_social_assessment
            or slip._l10n_sk_social_assessment_required()
        )
        others = self - covered
        if others:
            super(Payslip, others).action_payslip_done()
        done = covered.filtered(lambda slip: slip.state == "done")
        for slip in done.filtered("l10n_sk_social_assessment"):
            slip._l10n_sk_checked_social_assessment()
        unposted = covered - done
        if not unposted:
            return True
        if not self.env.context.get("without_compute_sheet"):
            unposted.filtered(
                lambda slip: not slip.prevent_compute_on_confirm
            ).compute_sheet()
        for slip in unposted:
            if slip._l10n_sk_social_assessment_required():
                slip._l10n_sk_checked_social_assessment(current=True)
        return super(
            Payslip, unposted.with_context(without_compute_sheet=True)
        ).action_payslip_done()

    def _l10n_sk_lock_social_payslips(self):
        self.check_access("write")
        if not self:
            return
        names = [
            "state",
            "employee_id",
            "l10n_sk_social_assessment",
            "l10n_sk_social_confirmed_at",
        ]
        self.flush_recordset(names)
        self.env.cr.execute(
            "SELECT id FROM hr_payslip WHERE id IN %s ORDER BY id FOR UPDATE",
            [tuple(sorted(self.ids))],
        )
        self.invalidate_recordset(names)
        self.employee_id._l10n_sk_lock_social_source()
