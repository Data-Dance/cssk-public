"""Reviewed tax adjustments/annexes feed the existing DPPO calculation.

These are tax workpapers, not another accounting ledger. Native accounting
continues to supply r100 and the statutory tax spine. This module supplies
the missing structured A/B input and reconciles the actual exported rows.
"""
import base64
import hashlib
import json
from decimal import Decimal, InvalidOperation
from lxml import etree

from odoo import _, api, fields, models
from odoo.exceptions import UserError


def signature(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False,
                                    separators=(',', ':')).encode()).hexdigest()


class DppoAnnexes(models.Model):
    _inherit = 'cssk.income.tax.return'

    l10n_sk_annexes_enabled = fields.Boolean(string='Use reviewed Tables A and B')
    l10n_sk_annexes_reviewed = fields.Boolean(string='Complete Tables A and B reviewed')
    l10n_sk_annexes_evidence = fields.Text(string='Tax adjustment and depreciation workpaper evidence')
    l10n_sk_annex_a_ids = fields.One2many('l10n.sk.dppo.annex.a.line', 'return_id', copy=True,
                                        string='Table A non-deductible expenses')
    l10n_sk_annex_b_book = fields.Monetary(string='B1 Accounting depreciation of tangible assets')
    l10n_sk_annex_b_tax = fields.Monetary(string='B2 Tax depreciation before B3/B4 and excluding B5')
    l10n_sk_annex_b_rent = fields.Monetary(string='B3 Unclaimed depreciation of rented assets')
    l10n_sk_annex_b_suspended = fields.Monetary(string='B4 Suspended depreciation')
    l10n_sk_annex_b_sale = fields.Monetary(string='B5 Proportional depreciation in the year of sale')
    l10n_sk_annex_proof = fields.Json(readonly=True, copy=False)
    l10n_sk_annex_export_hash = fields.Char(readonly=True, copy=False)
    l10n_sk_annex_filed_proofs = fields.Json(readonly=True, copy=False)

    _annex_inputs = {'l10n_sk_annexes_enabled', 'l10n_sk_annexes_reviewed', 'l10n_sk_annexes_evidence',
        'l10n_sk_annex_a_ids', 'l10n_sk_annex_b_book', 'l10n_sk_annex_b_tax',
        'l10n_sk_annex_b_rent', 'l10n_sk_annex_b_suspended', 'l10n_sk_annex_b_sale'}
    _annex_generated = {'l10n_sk_annex_proof', 'l10n_sk_annex_export_hash', 'l10n_sk_annex_filed_proofs'}

    @api.model_create_multi
    def create(self, values_list):
        for values in values_list:
            if self._annex_generated & values.keys() or any('default_'+key in self.env.context for key in self._annex_generated):
                raise UserError(_('DPPO annex evidence is generated by calculation and export.'))
        return super().create(values_list)

    def _annex_editable(self):
        self.check_access('write')
        if not self:
            return
        self.env.cr.execute('SELECT id FROM cssk_income_tax_return WHERE id IN %s ORDER BY id FOR UPDATE', [tuple(self.ids)])
        self.invalidate_recordset()
        if any(rec.state not in ('draft', 'preview') for rec in self):
            raise UserError(_('Reset the unfiled DPPO to draft before changing its annex workpapers.'))
        if any(rec.company_id.id not in self.env.companies.ids for rec in self):
            raise UserError(_('Select the DPPO company before changing its annex workpapers.'))

    def write(self, values):
        if self._annex_generated & values.keys():
            raise UserError(_('DPPO annex evidence is generated by calculation and export.'))
        if self._annex_inputs & values.keys():
            self._annex_editable()
        if {'company_id', 'date_from', 'date_to', 'version_id', 'statement_type_id', 'original_return_id'} & values.keys():
            self.filtered(lambda rec: rec.l10n_sk_annexes_enabled or rec.l10n_sk_annex_proof)._annex_editable()
        if values.get('l10n_sk_annexes_enabled') is False and any(
                rec.l10n_sk_annex_proof or rec.l10n_sk_annex_filed_proofs for rec in self):
            raise UserError(_('Keep reviewed annexes enabled while their calculation or filing evidence is retained.'))
        return super().write(values)

    def _annex_money(self, value):
        try:
            amount = Decimal(str(value))
            if not amount.is_finite() or amount < 0 or amount != amount.quantize(Decimal('.01')):
                raise ValueError()
        except (ValueError, TypeError, InvalidOperation) as error:
            raise UserError(_('Use finite nonnegative annex amounts in whole eurocents.')) from error
        return amount

    def unlink(self):
        if any(rec.l10n_sk_annex_filed_proofs for rec in self):
            raise UserError(_('The active or filed DPPO annex XML must be retained.'))
        return super().unlink()

    def _annex_values(self):
        self.ensure_one()
        if self.version_id != self.env.ref('l10n_sk_dppo.dppo_version_2025') or self.country_id.code != 'SK':
            raise UserError(_('This annex layout requires the reviewed Slovak DPPOv25 edition.'))
        if not self.l10n_sk_annexes_reviewed or not self.l10n_sk_annexes_evidence:
            raise UserError(_('Review complete Tables A and B and retain the tax adjustment/depreciation evidence.'))
        a = {f'r{index:02d}': Decimal(0) for index in range(1, 17)}
        for line in self.l10n_sk_annex_a_ids:
            if line.company_id != self.company_id or not line.evidence:
                raise UserError(_('Each Table A item needs evidence in the DPPO company.'))
            a[line.row_code] += self._annex_money(line.amount)
        a['r17'] = sum(a.values(), Decimal(0))
        b = dict(zip(('r01', 'r02', 'r03', 'r04', 'r05'), (
            self._annex_money(getattr(self, key)) for key in ('l10n_sk_annex_b_book', 'l10n_sk_annex_b_tax',
                'l10n_sk_annex_b_rent', 'l10n_sk_annex_b_suspended', 'l10n_sk_annex_b_sale'))))
        b['r06'] = b['r02']-b['r03']-b['r04']+b['r05']
        if b['r06'] < 0:
            raise UserError(_('Table B6 cannot be negative. Reconcile B2, B3, B4 and B5.'))
        return {key: f'{value:.2f}' for key, value in a.items()}, {key: f'{value:.2f}' for key, value in b.items()}

    def _annex_source(self):
        self.ensure_one()
        self = self.with_company(self.company_id)
        a, b = self._annex_values()
        # Rechecking the posted ledger also catches a late invoice or reversal
        # after the DPPO calculation, without copying a second financial ledger.
        ledger = self.env['account.move.line'].search([
            ('company_id', '=', self.company_id.id), ('parent_state', '=', 'posted'),
            ('date', '>=', self.date_from), ('date', '<=', self.date_to)], order='id')
        facts = {'company': self.company_id.id, 'version': self.version_id.id,
            'template': hashlib.sha256(etree.tostring(self.version_id.xml_template_ref_id.sudo().with_context(
                lang='en_US')._get_combined_arch())).hexdigest(),
            'schema': hashlib.sha256(base64.b64decode(self.version_id.xml_schema_data)).hexdigest(),
            'company_header': {'name': self.company_id.name, 'vat': self.company_id.vat,
                'dic': getattr(self.company_id, 'l10n_sk_dic', False),
                'street': self.company_id.street, 'street2': self.company_id.street2,
                'zip': self.company_id.zip, 'city': self.company_id.city,
                'country': self.company_id.country_id.code},
            'from': str(self.date_from), 'to': str(self.date_to),
            'statement_type': self.statement_type_id.id, 'original_return': self.original_return_id.id,
            'review': self.l10n_sk_annexes_evidence, 'A': a, 'B': b,
            'items': [{'row': line.row_code, 'amount': line.amount, 'evidence': line.evidence}
                      for line in self.l10n_sk_annex_a_ids.sorted('id')],
            'ledger': signature([(line.id, str(line.date), line.account_id.id, line.account_id.code,
                                  line.account_id.account_type, line.balance) for line in ledger]),
            'rows': sorted([[line.code, line.value, line.is_overridden, line.manual_value] for line in self.line_ids])}
        return facts

    def action_compute_lines(self):
        with self.env.cr.savepoint():
            if self.l10n_sk_annexes_enabled:
                self._annex_editable()
                a, b = self._annex_values()
                previous = {row[0]: row[1:] for row in
                    (self.l10n_sk_annex_proof or {}).get('source', {}).get('rows', [])}
                for line in self.line_ids.filtered(lambda rec: rec.code in ('r130', 'r150', 'r250')):
                    # A prior generated override is refreshed from the changed
                    # workpaper. A newly conflicting manual edit is retained so
                    # the consistency check below can refuse it explicitly.
                    if previous.get(line.code) == [line.value, line.is_overridden, line.manual_value]:
                        line.is_overridden = False
            result = super().action_compute_lines()
            if self.l10n_sk_annexes_enabled:
                difference = Decimal(b['r01'])-Decimal(b['r06'])
                for code, amount in {'r130': Decimal(a['r17']), 'r150': max(difference, Decimal(0)),
                                     'r250': max(-difference, Decimal(0))}.items():
                    line = self.line_ids.filtered(lambda rec: rec.code == code)
                    if len(line) != 1 or (line.is_overridden and self.currency_id.compare_amounts(line.value, float(amount))):
                        raise UserError(_('Reconcile the manual main DPPO row with its reviewed Table A or B before calculation.'))
                    line.write({'value': float(amount), 'manual_value': float(amount), 'is_overridden': True,
                                'formula_note': _('Reviewed Table A/B workpaper')})
                self._compute_tax_spine()
                if self.original_return_id:
                    self._fill_dodatocne_differences()
                source = self._annex_source()
                super(DppoAnnexes, self).write({'l10n_sk_annex_proof': {'source': source, 'digest': signature(source)},
                                               'l10n_sk_annex_export_hash': False})
        return result

    def _check_annex_proof(self):
        self.ensure_one()
        proof = self.l10n_sk_annex_proof or {}
        if not proof or signature(proof.get('source')) != proof.get('digest'):
            raise UserError(_('Recalculate the reviewed DPPO annexes before export or filing.'))
        if proof['source'] != self._annex_source():
            raise UserError(_('The DPPO annex inputs, main rows or posted ledger changed. Recalculate before export or filing.'))
        return proof

    def _cssk_preflight_export(self):
        result = super()._cssk_preflight_export()
        if self.l10n_sk_annexes_enabled:
            self._check_annex_proof()
        return result

    def _cssk_render_context(self):
        context = super()._cssk_render_context()
        a, b = ({}, {})
        if self.l10n_sk_annexes_enabled:
            source = self._check_annex_proof()['source']
            a, b = source['A'], source['B']
        context.update(sk_annex_a=a, sk_annex_b=b)
        return context

    def _attach_xml(self, xml_bytes):
        super()._attach_xml(xml_bytes)
        if self.l10n_sk_annexes_enabled:
            super(DppoAnnexes, self).write({'l10n_sk_annex_export_hash': hashlib.sha256(xml_bytes).hexdigest()})

    def action_submit(self):
        for rec in self.filtered('l10n_sk_annexes_enabled'):
            rec._check_annex_proof()
            if (not rec.xml_attachment_id or hashlib.sha256(base64.b64decode(rec.xml_attachment_id.datas)).hexdigest()
                    != rec.l10n_sk_annex_export_hash):
                raise UserError(_('Export the exact validated DPPO annex XML before recording a filing.'))
        result = super().action_submit()
        for rec in self.filtered('l10n_sk_annexes_enabled'):
            history = dict(rec.l10n_sk_annex_filed_proofs or {})
            history[str(rec.submitted_attachment_id.id)] = {'proof': rec.l10n_sk_annex_proof,
                                                          'xml_hash': rec.l10n_sk_annex_export_hash}
            super(DppoAnnexes, rec).write({'l10n_sk_annex_filed_proofs': history})
        return result


class AnnexALine(models.Model):
    _name = 'l10n.sk.dppo.annex.a.line'
    _description = 'DPPO reviewed Table A expense item'
    _check_company_auto = True
    _order = 'row_code, id'

    return_id = fields.Many2one('cssk.income.tax.return', required=True, ondelete='cascade')
    company_id = fields.Many2one(related='return_id.company_id', store=True)
    currency_id = fields.Many2one(related='return_id.currency_id')
    row_code = fields.Selection([(f'r{index:02d}', f'A{index}') for index in range(1, 17)], required=True)
    amount = fields.Monetary(required=True)
    evidence = fields.Text(required=True)

    @api.model_create_multi
    def create(self, values_list):
        normalized = []
        for values in values_list:
            values = dict(values)
            values.setdefault('return_id', self.env.context.get('default_return_id'))
            parent = self.env['cssk.income.tax.return'].browse(values.get('return_id')).exists()
            if len(parent) != 1:
                raise UserError(_('Choose the DPPO return before adding a Table A item.'))
            parent._annex_editable()
            supplied = values.pop('company_id', self.env.context.get('default_company_id'))
            if supplied and supplied != parent.company_id.id:
                raise UserError(_('The Table A item must belong to its DPPO company.'))
            normalized.append(values)
        context = dict(self.env.context)
        context.pop('default_company_id', None)
        return super(AnnexALine, self.with_context(context)).create(normalized)

    def write(self, values):
        if {'return_id', 'company_id', 'currency_id'} & values.keys():
            raise UserError(_('Table A items cannot be reassigned to another return or company.'))
        self.return_id._annex_editable()
        return super().write(values)

    def unlink(self):
        self.return_id._annex_editable()
        return super().unlink()


class AnnexAttachment(models.Model):
    _inherit = 'ir.attachment'

    def _annex_returns(self):
        ids = self.filtered(lambda rec: rec.res_model == 'cssk.income.tax.return' and rec.res_id).mapped('res_id')
        return self.env['cssk.income.tax.return'].browse(ids).exists().filtered(
            lambda rec: rec.l10n_sk_annexes_enabled or rec.l10n_sk_annex_proof or rec.l10n_sk_annex_filed_proofs)

    def write(self, values):
        if self._annex_returns() and {'datas', 'raw', 'store_fname', 'db_datas', 'res_model', 'res_id',
                                      'company_id', 'public', 'access_token', 'res_field', 'type', 'url'} & values.keys():
            raise UserError(_('Retain the exact DPPO annex XML. Export a new snapshot instead of replacing this file.'))
        return super().write(values)

    def unlink(self):
        if any((rec.xml_attachment_id | rec.filed_history_ids) & self for rec in self._annex_returns()):
            raise UserError(_('The active or filed DPPO annex XML must be retained.'))
        return super().unlink()

    def _to_http_stream(self):
        for rec in self._annex_returns():
            rec.check_access('read')
            if rec.xml_attachment_id & self and str(self.id) not in (rec.l10n_sk_annex_filed_proofs or {}):
                rec._check_annex_proof()
        return super()._to_http_stream()
